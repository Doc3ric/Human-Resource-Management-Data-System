        <h2>1. Legal Basis for Data Processing</h2>
        <p>
            This Privacy Notice is issued pursuant to and in compliance with the following Philippine laws, regulations, and guidelines:
        </p>
        <ul>
            <li><strong>Republic Act No. 10173</strong> — Data Privacy Act of 2012 and its Implementing Rules and Regulations (IRR)</li>
            <li><strong>National Privacy Commission (NPC)</strong> issuances and advisory opinions</li>
            <li><strong>Republic Act No. 9710</strong> — Magna Carta of Women (sex-disaggregated reporting requirements)</li>
            <li><strong>Republic Act No. 6713</strong> — Code of Conduct and Ethical Standards for Public Officials and Employees</li>
            <li><strong>Civil Service Commission (CSC)</strong> rules on personnel records management</li>
        </ul>

        <div class="highlight-box">
            <i class="bi bi-info-circle-fill"></i>
            <p>
                The Provincial Government of Bukidnon is registered as a Personal Information Controller (PIC) with the
                National Privacy Commission. All personal data collected through HRMDS is processed on the lawful basis of
                <em>performance of a function vested by law</em> (Section 12(e), RA 10173).
            </p>
        </div>
    </div>

    {{-- What We Collect --}}
    <div class="card">
        <div class="section-tag"><i class="bi bi-database-fill"></i> Data Collected</div>
        <h2>2. Personal Data We Collect</h2>
        <p>HRMDS processes the following categories of personal data for personnel management purposes:</p>

        <h3>General Personal Information</h3>
        <ul>
            <li>Full name, date of birth, civil status, sex, and address</li>
            <li>Contact information (email address, mobile number)</li>
            <li>Government-issued identification numbers (e.g., GSIS, Pag-IBIG, PhilHealth, TIN)</li>
            <li>Educational background and civil service eligibility</li>
        </ul>

        <h3>Employment Information</h3>
        <ul>
            <li>Plantilla item number, position title, salary grade and step</li>
            <li>Office/department assignment and employment status</li>
            <li>Appointment documents and employment history</li>
            <li>Performance ratings (SPMS) and step increment records</li>
        </ul>

        <h3>Sensitive Personal Information (SPI)</h3>
        <ul>
            <li>PWD (Persons with Disability) status — for quota reporting under RA 7277</li>
            <li>Solo parent status — for leave and benefit entitlements under RA 8972</li>
            <li>Retirement eligibility date (derived from date of birth and service record)</li>
        </ul>

        <div class="legal-ref"><i class="bi bi-bookmark-fill"></i> Authority: Section 3(l), RA 10173 — Definition of Sensitive Personal Information</div>
    </div>

    {{-- Purpose --}}
    <div class="card">
        <div class="section-tag"><i class="bi bi-bullseye"></i> Purpose</div>
        <h2>3. Purposes of Processing</h2>
        <p>Your personal data is processed exclusively for the following lawful purposes:</p>
        <ul>
            <li>Maintenance of official personnel records as required by the Civil Service Commission</li>
            <li>Administration of compensation, benefits, and leave entitlements</li>
            <li>Generation of GAD (Gender and Development) statistical reports pursuant to RA 9710</li>
            <li>Recruitment, selection, and appointment processes</li>
            <li>Retirement, separation, and end-of-service processing</li>
            <li>Compliance with audit, investigation, and legal proceedings</li>
            <li>Step increment monitoring and salary adjustments</li>
        </ul>
    </div>

    {{-- Data Sharing --}}
    <div class="card">
        <div class="section-tag"><i class="bi bi-arrow-left-right"></i> Data Sharing</div>
        <h2>4. Data Sharing and Disclosure</h2>
        <p>
            Personal data may be shared only with the following entities, to the minimum extent necessary, and
            subject to data sharing agreements:
        </p>
        <ul>
            <li><strong>Civil Service Commission (CSC)</strong> — for plantilla and appointment submissions</li>
            <li><strong>Commission on Audit (COA)</strong> — for audit examination of payroll and personnel records</li>
            <li><strong>Philippine Statistics Authority (PSA)</strong> — for statistical reporting (anonymized/aggregated)</li>
            <li><strong>GSIS, Pag-IBIG, PhilHealth</strong> — for benefit enrolment and claim processing</li>
            <li><strong>National Privacy Commission (NPC)</strong> — upon lawful request or in response to data breach notification</li>
        </ul>
        <p style="margin-top:10px;">Personal data is <strong>never sold, rented, or shared for commercial purposes.</strong></p>
    </div>

    {{-- Data Subject Rights --}}
    <div class="card">
        <div class="section-tag"><i class="bi bi-person-check-fill"></i> Your Rights</div>
        <h2>5. Rights of Data Subjects</h2>
        <p>Under RA 10173, you have the following rights with respect to your personal data:</p>
        <ul>
            <li><strong>Right to be informed</strong> — You have the right to know how your data is processed.</li>
            <li><strong>Right to access</strong> — You may request a copy of personal data held about you.</li>
            <li><strong>Right to rectification</strong> — You may request correction of inaccurate data.</li>
            <li><strong>Right to erasure</strong> — Where data is no longer necessary for its stated purpose, you may request its deletion (subject to legal retention requirements).</li>
            <li><strong>Right to object</strong> — You may object to automated processing that significantly affects you.</li>
            <li><strong>Right to damages</strong> — You may claim compensation for damages resulting from violations of RA 10173.</li>
        </ul>
        <p style="margin-top:10px;">
            To exercise these rights, contact the <strong>PHRMO Data Privacy Officer</strong> or the
            <strong>Provincial Information and Communications Technology Services (ICTS)</strong>.
        </p>
    </div>

    {{-- Security --}}
    <div class="card">
        <div class="section-tag"><i class="bi bi-lock-fill"></i> Security</div>
        <h2>6. Security Measures</h2>
        <p>The Provincial Government of Bukidnon implements organizational, physical, and technical security measures including:</p>
        <ul>
            <li>Role-based access control — users access only data within their authorized scope</li>
            <li>Encrypted data transmission (HTTPS/TLS)</li>
            <li>Comprehensive audit trail logging of all data access and modifications</li>
            <li>Automatic session expiry and forced re-authentication</li>
            <li>Encrypted database backups stored on secured cloud storage</li>
            <li>Regular security reviews and vulnerability assessments</li>
        </ul>

        <div class="highlight-box">
            <i class="bi bi-exclamation-triangle-fill" style="color:#d97706;"></i>
            <p style="color:#78350f;">
                Unauthorized access to this system is a criminal offense under Section 28, RA 10173,
                punishable by imprisonment of not less than one (1) year and a fine of not less than
                ₱500,000. All access attempts are logged and monitored.
            </p>
        </div>
    </div>

    {{-- Retention --}}
    <div class="card">
        <div class="section-tag"><i class="bi bi-clock-history"></i> Retention</div>
        <h2>7. Data Retention</h2>
        <p>
            Personnel records are retained in accordance with the <strong>Records Disposition Schedule (RDS)</strong>
            approved by the National Archives of the Philippines:
        </p>
        <ul>
            <li>Active employee records — retained for the duration of employment plus 10 years</li>
            <li>Separated/retired employee records — retained for 10 years post-separation</li>
            <li>Recruitment/applicant records — retained for 3 years if not appointed</li>
            <li>Audit logs — retained for 5 years</li>
        </ul>
    </div>

